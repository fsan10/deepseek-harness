CREATE SCHEMA IF NOT EXISTS dim;

CREATE TABLE IF NOT EXISTS dim.dim_business_owner (
    business_owner_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_owner_name VARCHAR(128) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS dim.dim_influencer_business_assignment_monthly (
    platform_code VARCHAR(32) NOT NULL,
    platform_name VARCHAR(64) NOT NULL,
    influencer_id VARCHAR(128) NOT NULL,
    influencer_name VARCHAR(255) NOT NULL,
    effective_month DATE NOT NULL,
    business_owner_id BIGINT,
    assignment_source VARCHAR(32) NOT NULL,
    source_file_name VARCHAR(255),
    source_shop_names TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    note TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (platform_code, influencer_id, effective_month),
    CONSTRAINT fk_influencer_assignment_business_owner
        FOREIGN KEY (business_owner_id)
        REFERENCES dim.dim_business_owner (business_owner_id),
    CONSTRAINT ck_influencer_assignment_effective_month
        CHECK (effective_month = DATE_TRUNC('month', effective_month)::date)
);

ALTER TABLE dim.dim_influencer_business_assignment_monthly
    ADD COLUMN IF NOT EXISTS is_active BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE IF NOT EXISTS dim.dim_business_gmv_target_monthly (
    target_month DATE NOT NULL,
    business_owner_id BIGINT NOT NULL,
    gmv_target NUMERIC(18,2) NOT NULL,
    note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (target_month, business_owner_id),
    CONSTRAINT fk_business_gmv_target_owner
        FOREIGN KEY (business_owner_id)
        REFERENCES dim.dim_business_owner (business_owner_id),
    CONSTRAINT ck_business_gmv_target_month
        CHECK (target_month = DATE_TRUNC('month', target_month)::date),
    CONSTRAINT ck_business_gmv_target_nonnegative
        CHECK (gmv_target >= 0)
);

