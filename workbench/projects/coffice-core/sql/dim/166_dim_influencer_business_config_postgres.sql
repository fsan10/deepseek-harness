COMMENT ON COLUMN dim.dim_business_owner.is_active IS '是否可用；停用后保留历史归属和目标。';
COMMENT ON COLUMN dim.dim_business_owner.created_at IS '商务记录创建时间。';
COMMENT ON COLUMN dim.dim_business_owner.updated_at IS '商务记录最后修改时间。';

