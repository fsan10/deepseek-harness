-- 早期网页新增商品使用了过长的 PRD-MANUAL UUID。公司商品 ID 不承载业务
-- 含义，迁移时保留 UUID 的前16位并统一到现有 PRD-CODE 短格式。
DROP TABLE IF EXISTS pg_temp.company_product_id_migration;
CREATE TEMP TABLE company_product_id_migration ON COMMIT DROP AS
SELECT
    product_id AS old_product_id,
    'PRD-CODE-' || SUBSTRING(
        REGEXP_REPLACE(product_id, '^PRD-MANUAL-', '', 'i') FROM 1 FOR 16
    ) AS new_product_id
FROM dim.dim_influencer_product
WHERE product_id LIKE 'PRD-MANUAL-%';

DO $guard$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM company_product_id_migration migration
        JOIN dim.dim_influencer_product product
          ON product.product_id = migration.new_product_id
         AND product.product_id <> migration.old_product_id
    ) THEN
        RAISE EXCEPTION '短商品ID与现有公司商品冲突，停止迁移';
    END IF;
END
$guard$;

ALTER TABLE dim.dim_company_product_code_mapping
    DROP CONSTRAINT IF EXISTS fk_company_product_code_mapping_product;

UPDATE dim.dim_influencer_product product
SET product_id = migration.new_product_id,
    updated_at = NOW()
FROM company_product_id_migration migration
WHERE product.product_id = migration.old_product_id;

UPDATE dim.dim_company_product_code_mapping mapping
SET product_id = migration.new_product_id,
    updated_at = NOW()
FROM company_product_id_migration migration
WHERE mapping.product_id = migration.old_product_id;

DO $migrate_fact_references$
DECLARE
    target RECORD;
BEGIN
    FOR target IN
        SELECT table_schema, table_name, column_name
        FROM information_schema.columns
        WHERE table_schema IN ('dws', 'ads')
          AND column_name IN ('product_id', 'company_product_id')
          AND data_type IN ('character varying', 'text')
    LOOP
        EXECUTE FORMAT(
            'UPDATE %I.%I target SET %I = migration.new_product_id '
            'FROM company_product_id_migration migration '
            'WHERE target.%I = migration.old_product_id',
            target.table_schema,
            target.table_name,
            target.column_name,
            target.column_name
        );
    END LOOP;
END
$migrate_fact_references$;

ALTER TABLE dim.dim_company_product_code_mapping
    ADD CONSTRAINT fk_company_product_code_mapping_product
    FOREIGN KEY (product_id)
    REFERENCES dim.dim_influencer_product (product_id)
    ON DELETE RESTRICT;

COMMENT ON COLUMN dim.dim_influencer_product.product_id IS
    '公司商品内部稳定主键；统一格式为PRD-CODE-加16位大写十六进制，创建后不随名称或业务编码变化。';
