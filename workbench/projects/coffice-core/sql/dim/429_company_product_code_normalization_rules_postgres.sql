CREATE SCHEMA IF NOT EXISTS dim;

CREATE TABLE IF NOT EXISTS dim.dim_company_product_code_normalization_rule (
    normalization_rule_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code_component VARCHAR(512) NOT NULL,
    normalized_code_expression VARCHAR(1024) NOT NULL,
    note VARCHAR(500),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_company_product_code_normalization_source_not_blank
        CHECK (BTRIM(source_code_component) <> ''),
    CONSTRAINT ck_company_product_code_normalization_target_not_blank
        CHECK (BTRIM(normalized_code_expression) <> ''),
    CONSTRAINT ck_company_product_code_normalization_target_parts
        CHECK (normalized_code_expression !~ '(^\+|\+$|\+\+)')
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_company_product_code_normalization_source
    ON dim.dim_company_product_code_normalization_rule (
        UPPER(BTRIM(source_code_component))
    );
CREATE INDEX IF NOT EXISTS idx_company_product_code_normalization_active
    ON dim.dim_company_product_code_normalization_rule (is_active, updated_at DESC);

COMMENT ON TABLE dim.dim_company_product_code_normalization_rule IS
    '公司级原始编码组件修正规则；在组合装拆分后、商品身份和数量解析前，把仓库手工漏分隔等异常组件改写为一个或多个标准组件。';
COMMENT ON COLUMN dim.dim_company_product_code_normalization_rule.normalization_rule_id IS
    '编码修正规则代理主键。';
COMMENT ON COLUMN dim.dim_company_product_code_normalization_rule.source_code_component IS
    '待修正的完整原始编码组件，忽略大小写和首尾空格后公司内唯一。';
COMMENT ON COLUMN dim.dim_company_product_code_normalization_rule.normalized_code_expression IS
    '修正后的标准组件表达；多个组件使用加号分隔，随后逐项解析商品身份与数量。';
COMMENT ON COLUMN dim.dim_company_product_code_normalization_rule.note IS
    '规则业务说明或异常来源备注。';
COMMENT ON COLUMN dim.dim_company_product_code_normalization_rule.is_active IS
    '规则是否启用；停用后保留审计但不参与编码修正。';
COMMENT ON COLUMN dim.dim_company_product_code_normalization_rule.created_at IS
    '规则创建时间。';
COMMENT ON COLUMN dim.dim_company_product_code_normalization_rule.updated_at IS
    '规则最后修改时间。';

