CREATE SCHEMA IF NOT EXISTS dim;

CREATE TABLE IF NOT EXISTS dim.dim_platform_shop_company (
    shop_company_sk BIGINT GENERATED BY DEFAULT AS IDENTITY,
    platform_code VARCHAR(32) NOT NULL,
    platform_name VARCHAR(64) NOT NULL,
    company_code VARCHAR(32) NOT NULL,
    company_name VARCHAR(255) NOT NULL,
    shop_code VARCHAR(128) NOT NULL,
    shop_name VARCHAR(255) NOT NULL,
    shop_type VARCHAR(64) NOT NULL,
    account_id VARCHAR(128) NOT NULL,
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    valid_from DATE NOT NULL DEFAULT DATE '1900-01-01',
    valid_to DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    shop_identity_key VARCHAR(161) GENERATED ALWAYS AS (
        LOWER(BTRIM(platform_code)) || '|' || BTRIM(shop_code)
    ) STORED,

    PRIMARY KEY (shop_company_sk),
    CONSTRAINT uq_dim_platform_shop_company_version
        UNIQUE (platform_code, shop_code, valid_from),
    CONSTRAINT ck_dim_platform_shop_company_valid_period
        CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

ALTER TABLE dim.dim_platform_shop_company
    ADD COLUMN IF NOT EXISTS shop_company_sk BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ADD COLUMN IF NOT EXISTS shop_identity_key VARCHAR(161) GENERATED ALWAYS AS (
        LOWER(BTRIM(platform_code)) || '|' || BTRIM(shop_code)
    ) STORED;

DO $$
DECLARE
    primary_key_name TEXT;
    primary_key_columns TEXT;
BEGIN
    SELECT c.conname, pg_get_constraintdef(c.oid)
      INTO primary_key_name, primary_key_columns
    FROM pg_constraint c
    WHERE c.conrelid = 'dim.dim_platform_shop_company'::regclass
      AND c.contype = 'p';

    IF primary_key_columns LIKE '%platform_code, shop_code%' THEN
        EXECUTE format('ALTER TABLE dim.dim_platform_shop_company DROP CONSTRAINT %I', primary_key_name);
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint c
        WHERE c.conrelid = 'dim.dim_platform_shop_company'::regclass
          AND c.contype = 'p'
    ) THEN
        ALTER TABLE dim.dim_platform_shop_company
            ADD CONSTRAINT pk_dim_platform_shop_company PRIMARY KEY (shop_company_sk);
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_dim_platform_shop_company_version
    ON dim.dim_platform_shop_company (platform_code, shop_code, valid_from);

CREATE UNIQUE INDEX IF NOT EXISTS uq_dim_platform_shop_company_current
    ON dim.dim_platform_shop_company (shop_identity_key)
    WHERE is_active AND valid_to IS NULL;

