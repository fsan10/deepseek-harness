CREATE SCHEMA IF NOT EXISTS dim;

CREATE TABLE IF NOT EXISTS dim.dim_company_influencer (
    company_influencer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_influencer_name VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT ck_company_influencer_name_not_blank
        CHECK (BTRIM(company_influencer_name) <> '')
);

CREATE TABLE IF NOT EXISTS dim.dim_company_influencer_source_mapping (
    mapping_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_influencer_id BIGINT NOT NULL,
    platform_code VARCHAR(32) NOT NULL,
    source_influencer_id VARCHAR(128) NOT NULL,
    source_influencer_name_snapshot VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_company_influencer_source_mapping_master
        FOREIGN KEY (company_influencer_id)
        REFERENCES dim.dim_company_influencer (company_influencer_id)
        ON DELETE RESTRICT,
    CONSTRAINT uq_company_influencer_source_identity
        UNIQUE (platform_code, source_influencer_id),
    CONSTRAINT ck_company_influencer_source_platform_not_blank
        CHECK (BTRIM(platform_code) <> ''),
    CONSTRAINT ck_company_influencer_source_id_not_blank
        CHECK (BTRIM(source_influencer_id) <> ''),
    CONSTRAINT ck_company_influencer_source_name_not_blank
        CHECK (BTRIM(source_influencer_name_snapshot) <> '')
);

CREATE TABLE IF NOT EXISTS dim.dim_company_influencer_business_assignment_monthly (
    company_influencer_id BIGINT NOT NULL,
    effective_month DATE NOT NULL,
    business_owner_id BIGINT,
    assignment_source VARCHAR(32) NOT NULL DEFAULT 'web',
    note TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (company_influencer_id, effective_month),
    CONSTRAINT fk_company_influencer_assignment_master
        FOREIGN KEY (company_influencer_id)
        REFERENCES dim.dim_company_influencer (company_influencer_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_company_influencer_assignment_owner
        FOREIGN KEY (business_owner_id)
        REFERENCES dim.dim_business_owner (business_owner_id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_company_influencer_assignment_month
        CHECK (effective_month = DATE_TRUNC('month', effective_month)::date),
    CONSTRAINT ck_company_influencer_assignment_source
        CHECK (assignment_source IN ('legacy_migration', 'web', 'merge_resolution'))
);

CREATE INDEX IF NOT EXISTS idx_company_influencer_name
    ON dim.dim_company_influencer (LOWER(BTRIM(company_influencer_name)), is_active);
CREATE INDEX IF NOT EXISTS idx_company_influencer_source_master
    ON dim.dim_company_influencer_source_mapping (company_influencer_id, is_active);
CREATE INDEX IF NOT EXISTS idx_company_influencer_assignment_owner_month
    ON dim.dim_company_influencer_business_assignment_monthly (
        business_owner_id,
        effective_month
    );
CREATE INDEX IF NOT EXISTS idx_company_influencer_assignment_lookup
    ON dim.dim_company_influencer_business_assignment_monthly (
        company_influencer_id,
        effective_month DESC
    );

