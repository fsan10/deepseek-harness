COMMENT ON COLUMN dim.dim_influencer_product_category.category_name IS '商品品类名称，忽略大小写和首尾空格后全局唯一。';
COMMENT ON COLUMN dim.dim_influencer_product_category.is_active IS '品类是否启用；停用品类时同事务停用其下全部产品。';
COMMENT ON COLUMN dim.dim_influencer_product_category.created_at IS '品类记录创建时间，带时区。';
COMMENT ON COLUMN dim.dim_influencer_product_category.updated_at IS '品类记录最后修改时间，带时区。';

