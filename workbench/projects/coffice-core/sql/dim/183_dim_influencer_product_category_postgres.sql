CREATE SCHEMA IF NOT EXISTS dim;

CREATE TABLE IF NOT EXISTS dim.dim_influencer_product_category (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(128) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_influencer_product_category_name_not_blank
        CHECK (BTRIM(category_name) <> '')
);

CREATE TABLE IF NOT EXISTS dim.dim_influencer_product (
    product_id VARCHAR(128) PRIMARY KEY,
    category_id BIGINT NOT NULL,
    company_product_code VARCHAR(128),
    product_name VARCHAR(255) NOT NULL,
    product_type VARCHAR(32) NOT NULL DEFAULT 'merchandise',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_influencer_product_category
        FOREIGN KEY (category_id)
        REFERENCES dim.dim_influencer_product_category (category_id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_influencer_product_id_not_blank
        CHECK (BTRIM(product_id) <> ''),
    CONSTRAINT ck_influencer_product_name_not_blank
        CHECK (BTRIM(product_name) <> '')
);

CREATE INDEX IF NOT EXISTS idx_influencer_product_category_status
    ON dim.dim_influencer_product (category_id, is_active, created_at DESC);

ALTER TABLE dim.dim_influencer_product
    ADD COLUMN IF NOT EXISTS company_product_code VARCHAR(128),
    ADD COLUMN IF NOT EXISTS product_type VARCHAR(32) NOT NULL DEFAULT 'merchandise';

COMMENT ON TABLE dim.dim_influencer_product_category IS '达播运营商品分类基础表；层级字段、约束及历史迁移由203号SQL补齐。';
